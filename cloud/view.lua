local GradientDrawable = luajava.bindClass("android.graphics.drawable.GradientDrawable")
searchContainer:removeAllViews()
searchContainer:setOrientation(LinearLayout.HORIZONTAL)
searchContainer:setWeightSum(1)
searchContainer:setGravity(LinearLayout.VERTICAL)
local function createRoundBg(radius, bgColor, strokeW, strokeColor)
    local drawable = luajava.new(GradientDrawable)
    drawable:setShape(GradientDrawable.RECTANGLE)
    drawable:setCornerRadius(radius)
    drawable:setColor(bgColor)
    if strokeW and strokeColor then
        drawable:setStroke(strokeW, strokeColor)
    end
    return drawable
end
local etSearch = luajava.new(EditText, activity)
etSearch:setHint("搜索...")
etSearch:setTextSize(14)
etSearch:setTextColor(color("#333333"))
etSearch:setHintTextColor(color("#AAAAAA"))
etSearch:setBackground(nil)
local etRadius = dp(20)
local etBg = createRoundBg(etRadius, color("#FFFFFF"), dp(1), color("#E0E0E0"))
etSearch:setBackground(etBg)
etSearch:setPadding(dp(16), 0, dp(16), 0)
local etParams = luajava.new(LayoutParams, 0, dp(40), 1)
etParams:setMargins(0, 0, dp(8), 0)
etSearch:setLayoutParams(etParams)
