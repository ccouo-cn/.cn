local LinearLayout = luajava.bindClass("android.widget.LinearLayout")
local TextView = luajava.bindClass("android.widget.TextView")
local GradientDrawable = luajava.bindClass("android.graphics.drawable.GradientDrawable")
local ViewGroup = luajava.bindClass("android.view.ViewGroup")
local Color = luajava.bindClass("android.graphics.Color")
local context = categoryContainer:getContext()
categoryContainer:removeAllViews()
categoryContainer:setOrientation(LinearLayout.HORIZONTAL)
local categories = {"校园", "萌作", "猎奇", "治愈"}
for i, name in ipairs(categories) do
    local tv = luajava.new(TextView, context)
    tv:setText(name)
    tv:setTextSize(13)
    tv:setTextColor(0xFF333333)
    tv:setPadding(40, 20, 40, 20)
    local bg = luajava.new(GradientDrawable)
    bg:setShape(GradientDrawable.RECTANGLE)
    bg:setCornerRadius(40)
    bg:setColor(0xFFFCE4EC)
    bg:setStroke(2, 0xFFFF4081)
    tv:setBackground(bg)
    tv:setTextColor(0xFFFF4081)
    local params = luajava.new(ViewGroup.MarginLayoutParams, LinearLayout.LayoutParams.WRAP_CONTENT, LinearLayout.LayoutParams.WRAP_CONTENT)
    params.rightMargin = 24
    tv:setLayoutParams(params)
    tv:setOnClickListener(luajava.createProxy("android.view.View$OnClickListener", {
        onClick = function(v)
            toast("搜索: " .. name)
        end
    }))
    categoryContainer:addView(tv)
end
categoryContainer:requestLayout()
